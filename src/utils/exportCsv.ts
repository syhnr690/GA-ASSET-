export const exportMaintenanceTasksToCsv = (tasks: MaintenanceTask[], logs: MaintenanceLog[]) => {
  const taskHeaders = [
    'Kode Work Order',
    'Kode Aset',
    'Nama Aset',
    'Kategori',
    'Lokasi',
    'Jenis Tugas',
    'Tanggal Terjadwal',
    'Status',
    'Prioritas',
    'Vendor / Teknisi',
    'Estimasi Biaya',
    'Biaya Aktual',
    'Otomatis Oleh Sistem'
  ];

  const taskRows = tasks.map(t => [
    `"${t.workOrderCode}"`,
    `"${t.assetCode}"`,
    `"${t.assetName.replace(/"/g, '""')}"`,
    `"${t.category}"`,
    `"${t.location}"`,
    `"${t.taskType}"`,
    `"${t.scheduledDate}"`,
    `"${t.status}"`,
    `"${t.priority}"`,
    `"${t.technicianOrVendor}"`,
    t.estimatedCost,
    t.actualCost || 0,
    t.isAutoGenerated ? '"Ya (Sistem GA)"' : '"Manual"'
  ]);

  downloadCsv([taskHeaders.join(','), ...taskRows.map(r => r.join(','))].join('\n'), 'Jadwal_Perawatan_Rutin_GA.csv');
};

function downloadCsv(content: string, filename: string) {
  const blob = new Blob(['\uFEFF' + content], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
