export type AssetCategory = 
  | 'IT & Komputer'
  | 'Elektronik & Meeting'
  | 'Fasilitas & Gedung'
  | 'Mebel & Perabot'
  | 'Kendaraan Operasional'
  | 'Pantry & Kebersihan'
  | 'Peralatan Keamanan / K3';

export type AssetCondition = 'Baik' | 'Rusak Ringan' | 'Dalam Perbaikan' | 'Rusak Berat / Afkir';

export type AssetStatus = 'Tersedia' | 'Sedang Dipinjam' | 'Dalam Perawatan' | 'Dihapusbukukan';

export type MaintenanceFrequency = 'Bulanan' | 'Triwulan (3 Bulan)' | 'Semesteran (6 Bulan)' | 'Tahunan (12 Bulan)' | 'Khusus / Kustom';

export interface OfficeAsset {
  id: string;
  assetCode: string; // e.g. AST-IT-24-001
  name: string;
  category: AssetCategory;
  brand: string;
  model: string;
  serialNumber: string;
  location: string; // e.g. Lantai 2 - Ruang IT, Ruang Rapat Merapi
  department: string; // e.g. GA & Operasional, IT Support, Keuangan, HRD
  picName: string;
  purchaseDate: string; // YYYY-MM-DD
  purchasePrice: number; // in IDR
  warrantyExpiry: string; // YYYY-MM-DD
  condition: AssetCondition;
  status: AssetStatus;
  
  // Maintenance Automation
  hasRoutineMaintenance: boolean;
  maintenanceFrequency: MaintenanceFrequency;
  maintenanceIntervalMonths: number; // e.g. 3 for quarterly
  lastMaintenanceDate?: string;
  nextMaintenanceDate?: string; // computed automatically
  maintenanceVendor?: string;
  notes?: string;
  imageUrl?: string;
}

export type LoanStatus = 'Dipinjam' | 'Terlambat' | 'Dikembalikan';

export interface AssetLoan {
  id: string;
  loanCode: string; // e.g. PINJ-2026-001
  assetId: string;
  assetCode: string;
  assetName: string;
  borrowerName: string;
  borrowerEmployeeId: string; // NIK
  borrowerDepartment: string;
  borrowerContact: string; // Phone / WA
  purpose: string;
  borrowDate: string; // YYYY-MM-DD
  expectedReturnDate: string; // YYYY-MM-DD
  actualReturnDate?: string;
  status: LoanStatus;
  returnCondition?: AssetCondition;
  returnNotes?: string;
  gaApprover: string;
}

export type MaintenancePriority = 'Rendah' | 'Normal' | 'Tinggi' | 'Darurat / Kritis';
export type MaintenanceStatus = 'Terjadwal' | 'Mendekati Waktu' | 'Jatuh Tempo' | 'Terlambat' | 'Sedang Dikerjakan' | 'Selesai';

export interface MaintenanceTask {
  id: string;
  workOrderCode: string; // e.g. WO-MAINT-2026-08
  assetId: string;
  assetCode: string;
  assetName: string;
  category: AssetCategory;
  location: string;
  taskType: 'Pemeriksaan Berkala' | 'Servis Rutin' | 'Kalibrasi' | 'Pembersihan / Sanitasi' | 'Perbaikan Kerusakan';
  scheduledDate: string; // YYYY-MM-DD
  completedDate?: string;
  frequency: MaintenanceFrequency;
  priority: MaintenancePriority;
  status: MaintenanceStatus;
  technicianOrVendor: string;
  estimatedCost: number;
  actualCost?: number;
  actionItems: string[];
  findings?: string;
  completionNotes?: string;
  isAutoGenerated: boolean;
}

